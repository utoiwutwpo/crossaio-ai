DEFAULT_LANG = "en"


def identity_text(lang: str = DEFAULT_LANG) -> str:
    """返回目标语言的 AI 身份告知文本（Art.50(1)）。"""
    return AI_IDENTITY_DISCLOSURE.get((lang or DEFAULT_LANG).lower(),
                                      AI_IDENTITY_DISCLOSURE[DEFAULT_LANG])


def wrap_reply(reply: str, lang: str = DEFAULT_LANG, enabled: bool = True) -> str:
    """按 Art.50(1) 在回复上注入 AI 身份告知。

    - enabled=False：原样返回（用于测试或非欧盟场景）。
    - enabled=True：在回复末尾追加 [AI Act Art.50] 披露行，
      确保即便前端忽略结构化字段，买家仍能在对话中看到 AI 身份告知。
    """
    if not enabled:
        return reply
    return f"{reply}\n\n[AI Act Art.50] {identity_text(lang)}"


def content_marker() -> str:
    """Art.50(2) 机器可读标记（轻量落地）。

    前端可据此在消息元数据/水印层标记合成内容，满足「机器可读格式」要求。
    """
    return "ai-generated"


def supported_languages() -> list[str]:
    return list(AI_IDENTITY_DISCLOSURE.keys())
